export interface AccesorioTienda { id: string; donante: string; parte: ParteAccesorio; rareza: RarezaSobre; precio: number }
export const ACCESORIOS: readonly AccesorioTienda[] = LISTA.map(([id, donante, parte]) => {
  const r = rarezaPersonaje(donante), rareza: RarezaSobre = r === "comun" ? "rara" : r;
  return { id, donante, parte, rareza, precio: PRECIO_ACCESORIO[rareza] };
});
const POR_ID = new Map(ACCESORIOS.map(a => [a.id, a]));
export const accesorioPorId = (id: string) => POR_ID.get(id) ?? null;
/** La pieza del personalizador que corresponde: `${donante}--${parte}` es el mismo id de pieza v3. */
export const esCartaAccesorio = (id: string) => POR_ID.has(id);
